create table if not exists public.rsvps (
  id bigint generated by default as identity primary key,
  guest_name text not null check (char_length(guest_name) between 1 and 100),
  attendance text not null check (attendance in ('yes','no','maybe')),
  guest_count int not null default 1 check (guest_count between 1 and 6),
  user_agent text,
  submitted_at timestamptz not null default now()
);

alter table public.rsvps enable row level security;

-- Public mehmonlar yangi javob yuborishi mumkin; jadvalni o‘qiy olmaydi.
create policy "Anyone can submit RSVP"
on public.rsvps for insert
to anon, authenticated
with check (
  char_length(guest_name) between 1 and 100
  and attendance in ('yes','no','maybe')
  and guest_count between 1 and 6
);

